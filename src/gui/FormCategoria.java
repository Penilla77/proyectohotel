    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        try {
            String det = this.textDetalle.getText().trim();

            if (det.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Todos los campos son obligatorios", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
            if (det.length() > 30) {
                JOptionPane.showMessageDialog(this, "El detalle puede tener máximo 30 caracteres", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
            if (OperacionesCategoria.buscarPorDetalle(det) != null) {
                JOptionPane.showMessageDialog(this, "Ya existe una categoría con ese detalle", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }

            Categoria c = new Categoria(OperacionesCategoria.nuevoCod(), det);
            OperacionesCategoria.Guardar(c);
            JOptionPane.showMessageDialog(this, "Datos guardados correctamente.", "Éxito", JOptionPane.INFORMATION_MESSAGE);

            this.idSel = 0;
            this.textDetalle.setText("");
            this.tabla.setModel(OperacionesCategoria.modeloCategoria());
            Estilo.ajustarColumnas(this.tabla);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        try {
            String id = JOptionPane.showInputDialog(
                    this,
                    "Ingresar Código de la Categoría",
                    "Datos de la Categoría",
                    JOptionPane.QUESTION_MESSAGE);

            if (id == null || id.trim().isEmpty()) {
                JOptionPane.showMessageDialog(
                        this,
                        "Debe ingresar un Código",
                        "Error",
                        JOptionPane.ERROR_MESSAGE
                );
                return;
            }
            if (id.length() > 9) {
                JOptionPane.showMessageDialog(this, "El Código puede tener máximo 9 dígitos", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
            for (int i = 0; i < id.length(); i++) {
                if (!Character.isDigit(id.charAt(i))) {
                    JOptionPane.showMessageDialog(this, "El Código debe ser un número", "Error", JOptionPane.ERROR_MESSAGE);
                    return;
                }
            }
            Categoria c2 = (Categoria) OperacionesCategoria.buscar(Integer.parseInt(id.trim()));

            if (c2 != null) {
                this.idSel = c2.getCodCategoria();
                this.textDetalle.setText(c2.getDetalle());
                for (int i = 0; i < this.tabla.getRowCount(); i++) {
                    if ((int) this.tabla.getValueAt(i, 0) == this.idSel) {
                        this.tabla.setRowSelectionInterval(i, i);
                    }
                }
            } else {
                JOptionPane.showMessageDialog(
                        this,
                        "Categoría no encontrada",
                        "Error",
                        JOptionPane.ERROR_MESSAGE
                );
                this.idSel = 0;
                this.textDetalle.setText("");
            }
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
        try {
            if (this.idSel == 0) {
                JOptionPane.showMessageDialog(this, "Elige una categoría de la tabla o usa Buscar", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
            String det = this.textDetalle.getText().trim();

            if (det.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Todos los campos son obligatorios", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
            if (det.length() > 30) {
                JOptionPane.showMessageDialog(this, "El detalle puede tener máximo 30 caracteres", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
            if (OperacionesCategoria.esHabitacion(this.idSel)) {
                JOptionPane.showMessageDialog(this, "La categoría Habitación no se puede modificar", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
            Categoria otra = OperacionesCategoria.buscarPorDetalle(det);
            if (otra != null && otra.getCodCategoria() != this.idSel) {
                JOptionPane.showMessageDialog(this, "Ya existe otra categoría con ese detalle", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }

            if (OperacionesCategoria.modificar(this.idSel, det)) {
                JOptionPane.showMessageDialog(this, "Se ha modificado correctamente la categoría", "Éxito", JOptionPane.INFORMATION_MESSAGE);
            } else {
                JOptionPane.showMessageDialog(this, "Categoría no encontrada", "Error", JOptionPane.ERROR_MESSAGE);
            }

            this.idSel = 0;
            this.textDetalle.setText("");
            this.tabla.setModel(OperacionesCategoria.modeloCategoria());
            Estilo.ajustarColumnas(this.tabla);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnModificarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        try {
            if (this.idSel == 0) {
                JOptionPane.showMessageDialog(this, "Elige una categoría de la tabla o usa Buscar", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
            if (OperacionesCategoria.esHabitacion(this.idSel)) {
                JOptionPane.showMessageDialog(this, "La categoría Habitación no se puede eliminar", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
            int resp = JOptionPane.showConfirmDialog(this, "¿Eliminar la categoría " + OperacionesCategoria.detalle(this.idSel) + "?", "Confirmar", JOptionPane.YES_NO_OPTION);
            if (resp != JOptionPane.YES_OPTION) {
                return;
            }

            if (OperacionesCategoria.eliminar(this.idSel)) {
                JOptionPane.showMessageDialog(this, "Categoría eliminada correctamente", "Éxito", JOptionPane.INFORMATION_MESSAGE);
            } else {
                JOptionPane.showMessageDialog(this, "Categoría no encontrada", "Error", JOptionPane.ERROR_MESSAGE);
            }

            this.idSel = 0;
            this.textDetalle.setText("");
            this.tabla.setModel(OperacionesCategoria.modeloCategoria());
            Estilo.ajustarColumnas(this.tabla);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void tablaMouseReleased(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tablaMouseReleased
        try {
            int fila = this.tabla.getSelectedRow();
            if (fila >= 0) {
                this.idSel = (int) this.tabla.getValueAt(fila, 0);
                Categoria c = OperacionesCategoria.buscar(this.idSel);
                this.textDetalle.setText(c.getDetalle());
            }
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_tablaMouseReleased

