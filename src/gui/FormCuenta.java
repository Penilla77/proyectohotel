    private void btnCheckoutActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCheckoutActionPerformed
        try {
            if (this.idSel == 0) {
                JOptionPane.showMessageDialog(this, "Elige una cuenta de la tabla", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
            String pago = (String) this.comboPago.getSelectedItem();
            int resp = JOptionPane.showConfirmDialog(this, "¿Hacer el checkout de la cuenta " + this.idSel + "? Se cobra " + Tablas.dinero(Hotel.totalCuenta(this.idSel)) + " con " + pago + " y la habitación queda libre", "Confirmar", JOptionPane.YES_NO_OPTION);
            if (resp != JOptionPane.YES_OPTION) {
                return;
            }

            Factura fa = Hotel.checkout(this.idSel, pago);

            this.idSel = 0;
            this.comboPago.setSelectedIndex(0);
            this.tablaDetalle.setModel(OperacionesProductoVendido.modeloResumen(new LinkedList()));
            Estilo.ajustarColumnas(this.tablaDetalle);
            this.textTotal.setText("");
            this.tabla.setModel(OperacionesCuenta.modeloCuenta());
            Estilo.ajustarColumnas(this.tabla);

            JTextArea area = new JTextArea(fa.getDetalle(), 18, 62);
            area.setEditable(false);
            area.setFont(new java.awt.Font(java.awt.Font.MONOSPACED, java.awt.Font.PLAIN, 13));
            JOptionPane.showMessageDialog(this, new JScrollPane(area), "Factura", JOptionPane.INFORMATION_MESSAGE);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnCheckoutActionPerformed

    private void tablaMouseReleased(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tablaMouseReleased
        try {
            int fila = this.tabla.getSelectedRow();
            if (fila >= 0) {
                this.idSel = (int) this.tabla.getValueAt(fila, 0);
                Cuenta cu = OperacionesCuenta.buscar(this.idSel);
                this.tablaDetalle.setModel(OperacionesProductoVendido.modeloResumen(Hotel.lineasCuenta(cu)));
                Estilo.ajustarColumnas(this.tablaDetalle);
                this.textTotal.setText(Tablas.dinero(Hotel.totalCuenta(this.idSel)));
            }
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_tablaMouseReleased

